// Run after updating the source word lists. IDs and chapter/group order are preserved.
import { mkdir, writeFile } from 'node:fs/promises'
import { parseExtra } from '../src/pages/vocabulary/extraParser.ts'
import { synonymMeanings } from '../src/pages/vocabulary/synonymMeanings.ts'
import { synonymPosData } from '../src/pages/vocabulary/synonymPos.ts'
import vocabulary from '../src/pages/vocabulary/vocabulary.js'
import { wordSentences } from '../src/pages/vocabulary/wordSentences.ts'
const dir = new URL('../src/data/vocabulary/', import.meta.url)
await mkdir(dir, { recursive: true })
const pos = new Map()
for (const chapter of Object.values(vocabulary)) {
  for (const w of chapter.words.flat()) {
    const key = w.word[0].toLowerCase()
    if (w.pos && !pos.has(key)) pos.set(key, w.pos)
  }
}
const names = Object.keys(vocabulary)
const manifests = []
for (const [index, [name, chapter]] of Object.entries(vocabulary).entries()) {
  const id = String(index + 1).padStart(2, '0')
  const keys = new Set()
  for (const w of chapter.words.flat()) {
    for (const key of [...w.word, ...parseExtra(w.extra).map(e => e.word)]) keys.add(key.trim().toLowerCase())
  }
  const sentences = Object.fromEntries([...keys].filter(k => wordSentences[k]).map(k => [k, wordSentences[k]]))
  const synonyms = new Set(Object.values(sentences).flatMap(w => w.syn).map(w => w.trim().toLowerCase()))
  const meanings = Object.fromEntries([...synonyms].filter(k => synonymMeanings[k]).map(k => [k, synonymMeanings[k]]))
  const positions = Object.fromEntries([...synonyms].filter(k => pos.get(k) || synonymPosData[k]).map(k => [k, pos.get(k) || synonymPosData[k]]))
  await writeFile(new URL(`${id}.json`, dir), `${JSON.stringify(chapter)  }\n`)
  await writeFile(new URL(`${id}-info.json`, dir), `${JSON.stringify({ sentences, meanings, positions })  }\n`)
  manifests.push(`  ${JSON.stringify(name)}: { words: () => import('./${id}.json'), info: () => import('./${id}-info.json') },`)
}
await writeFile(new URL('manifest.ts', dir), `// Generated by scripts/split-vocabulary.mjs.\nexport const chapters = ${JSON.stringify(names)} as const\nexport const chapterLoaders = {\n${manifests.join('\n')}\n}\n`)
console.log(`Generated ${names.length} chapters, ${Object.values(vocabulary).flatMap(c => c.words.flat()).length} entries`)
